#!/usr/bin/env node
'use strict';
/**
 * reviewer.js — goal 1: the resume reviewer skill.
 *
 * Reads a Markdown / plain-text resume, scores every bullet against the Google-XYZ
 * rubric (via lib/xyz.js — the shared contract), and prints a per-bullet scorecard
 * with rewrite suggestions. It never edits your original resume.
 *
 * With --docx it ALSO writes a NEW .docx containing the suggested improved bullets
 * (weak bullets replaced by their XYZ rewrite; full-XYZ bullets kept as-is). The
 * rewrites are deterministic scaffolds — fill the [bracketed] placeholders in.
 *
 * Usage:
 *   node skills/reviewer/reviewer.js <resume.md> [--json] [--out <file>] [--docx <out.docx>]
 *   node skills/reviewer/reviewer.js --stdin < resume.md
 */
const fs = require('fs');
const path = require('path');
const { reviewResume, formatReport, scoreBullet } = require('../../lib/xyz');
const { writeResumeDocx } = require('../../lib/docx');

function parseArgs(argv) {
  const args = { json: false, stdin: false, out: null, file: null, docx: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--json') args.json = true;
    else if (a === '--stdin') args.stdin = true;
    else if (a === '--out') args.out = argv[++i];
    else if (a === '--docx') args.docx = argv[++i];
    else if (!a.startsWith('--')) args.file = a;
  }
  return args;
}

function readInput(args) {
  if (args.stdin) return fs.readFileSync(0, 'utf8');
  if (!args.file) {
    console.error('Usage: reviewer.js <resume.md> [--json] [--out <file>] [--docx <out.docx>] | --stdin');
    process.exit(2);
  }
  return fs.readFileSync(path.resolve(args.file), 'utf8');
}

/** Per-bullet transform for the .docx: use the XYZ rewrite when a bullet isn't full 3/3. */
function improveBullet(text) {
  const b = scoreBullet(text);
  return b.score === 3 ? text : (b.rewrite || text);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const md = readInput(args);
  const review = reviewResume(md);
  const output = args.json ? JSON.stringify(review, null, 2) : formatReport(review);

  if (args.out) {
    fs.writeFileSync(path.resolve(args.out), output);
    console.error(`Wrote ${args.json ? 'JSON' : 'scorecard'} to ${args.out}`);
  } else if (!args.docx) {
    process.stdout.write(output + '\n');
  }

  if (args.docx) {
    const note = 'Draft resume — suggested XYZ improvements. Replace every [bracketed] placeholder with a real number before sending. Generated by the resume reviewer; review before use.';
    const out = await writeResumeDocx(md, improveBullet, args.docx, note);
    console.error(`Wrote improved-resume .docx to ${path.relative(process.cwd(), out)}`);
  }

  if (review.summary.totalBullets === 0) {
    console.error('No bullet lines found — is this a Markdown/plain-text resume with "- " bullets?');
    process.exit(1);
  }
}

if (require.main === module) main();
module.exports = { parseArgs, improveBullet };
